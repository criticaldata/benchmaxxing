"""Cascade-onset distribution, text lane baseline-relative arm (#174, part a). Pure re-analysis
of the already-committed `_repro_shared.jsonl` transcripts; zero API calls.

The plan's flagship reusable artifact is `benchmaxxing.onset.cascade_onset`: it detects the turn
where a committee tips from following the evidence to following a planted seed. It is exported
and unit-tested but was never reported on committed data - this reports it for the baseline-
relative arm (the ORIGINAL, non-anchored seed design: one committee member proposes a wrong
answer once, seeded, then every subsequent turn is scored against that seed vs the group's own
evidence-based answer).

**Uses `_repro_shared.jsonl`, not the plain `_shared.jsonl` the issue names.** The plain
`medqa-*_shared.jsonl` transcripts predate the answer-parser fix (last touched in the original
`5d9e991` commit, never regenerated); `_repro_shared.jsonl` was generated by `reproduce.py`'s
verifier pass AFTER the fix (commit `a0841ed`) and is what `cascade_results.json`'s own `onset`
field is already computed from. Using the corrected transcripts avoids re-deriving an onset
distribution from potentially mis-parsed per-turn answers.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from benchmaxxing.onset import cascade_onset
from benchmaxxing.transcript import load_transcript


def _cascade_series(transcript, seed_answer, evidence_answer):
    """Per-turn (agree-with-seed - agree-with-evidence) series, plus the real turn index behind
    each entry. Same construction as `benchmaxxing.ablations._cascade_series`, inlined here since
    that helper is private to its module."""
    ordered = sorted(transcript.turns, key=lambda t: t.turn_index)
    series, turn_indices = [], []
    for turn in ordered:
        if turn.answer is None:
            continue
        agree_seed = 1.0 if turn.answer == seed_answer else 0.0
        agree_evidence = 1.0 if turn.answer == evidence_answer else 0.0
        series.append(agree_seed - agree_evidence)
        turn_indices.append(turn.turn_index)
    return series, turn_indices


def _case_onset(transcript):
    seeded_turns = [t for t in transcript.turns if t.seeded and t.answer is not None]
    if not seeded_turns:
        return None, None, None
    seed_answer = seeded_turns[0].answer
    # Evidence = the group's own answer: the majority committed value among non-seed agents.
    non_seed_committed = [v for k, v in transcript.committed.items() if k != seeded_turns[0].agent_id]
    if not non_seed_committed:
        return None, seed_answer, None
    evidence_answer = max(set(non_seed_committed), key=non_seed_committed.count)

    series, turn_indices = _cascade_series(transcript, seed_answer, evidence_answer)
    idx = cascade_onset(series, min_size=1)
    onset_turn = turn_indices[idx] if idx is not None and 0 <= idx < len(turn_indices) else None
    return onset_turn, seed_answer, evidence_answer


def main():
    ap = argparse.ArgumentParser(
        description="Cascade-onset distribution over a dataset's committed shared transcripts."
    )
    ap.add_argument(
        "--results-dir", default=str(Path(__file__).parent / "results"),
        help="results dir with cascade_results.json and transcripts/ (default: the MedQA lane)",
    )
    ap.add_argument("--label", default="MedQA", help="dataset label for the report text")
    args = ap.parse_args()

    results_dir = Path(args.results_dir)
    transcript_dir = results_dir / "transcripts"
    summary = json.loads((results_dir / "cascade_results.json").read_text())
    case_ids = [c["case_id"] for c in summary["per_case"]]

    rows = []
    for case_id in case_ids:
        path = transcript_dir / f"{case_id}_repro_shared.jsonl"
        transcript = load_transcript(path)
        onset_turn, seed_answer, evidence_answer = _case_onset(transcript)
        rows.append({
            "case_id": case_id, "onset_turn": onset_turn,
            "seed_matches_evidence": seed_answer == evidence_answer,
        })

    onsets = [r["onset_turn"] for r in rows if r["onset_turn"] is not None]
    censored = sum(1 for r in rows if r["onset_turn"] is None)
    seed_invalid = sum(1 for r in rows if r["seed_matches_evidence"])
    distinct = sorted(set(onsets))

    # cascade_results.json spells the adoption rates mean_shared_adopt/mean_isolated_adopt; older
    # runs used shared_adoption/isolated_adoption. Accept either so this reads on any lane.
    shared = summary.get("mean_shared_adopt", summary.get("shared_adoption"))
    isolated = summary.get("mean_isolated_adopt", summary.get("isolated_adoption"))
    contagion = summary.get("mean_contagion")
    if contagion is None and shared is not None and isolated is not None:
        contagion = round(shared - isolated, 6)

    out = {
        "dataset": args.label,
        "n": len(rows), "n_censored": censored, "n_seed_equals_evidence": seed_invalid,
        "onset_turn_distribution": onsets,
        "distinct_onset_turns": distinct,
        "contagion_shared_minus_isolated": contagion,
        "per_case": rows,
    }

    # the original MedQA v1 run also carried a known-tainted anchored arm; include it only when the
    # file is present (it is a MedQA-specific artifact, absent for a clean replication like MedMCQA)
    v2 = results_dir / "cascade_v2_per_case.jsonl"
    if v2.exists():
        v2_rows = [json.loads(line) for line in v2.read_text().splitlines() if line.strip()]
        out["v2_anchored_arm_onset_distribution_TAINTED"] = {
            "onsets": [r["onset"] for r in v2_rows],
            "caveat": (
                "cascade_v2_per_case.jsonl (the anchored/case-anchored seed arm) is confirmed "
                "tainted by the pre-fix stray-article answer parser; reported only because the "
                "template issue asks for it, not treated as a trustworthy distribution."
            ),
        }

    where = (
        f"every detected onset lands on the same turn index ({distinct[0]})" if len(distinct) <= 1 and distinct
        else f"detected onsets spread across turns {distinct}"
    )
    out["read"] = (
        f"{args.label}: onset is detected (not censored) on {len(onsets)} of {len(rows)} cascade "
        f"cases, and {where}. A single detected turn immediately after the seeded agent's one-off "
        "wrong turn is the trivial detection of a transient blip, not a sustained tipping point: "
        "the other agents do not adopt the seed at any later turn, so there is no regime change for "
        f"a change-point detector to find. {seed_invalid} of {len(rows)} cases have the seed answer "
        "equal to the group's own evidence answer (a trivially invalid seed for that case). "
        "Contagion for this arm is the shared-minus-isolated adoption gap already in "
        f"cascade_results.json (contagion {contagion}, shared {shared}, isolated {isolated})."
    )
    (results_dir / "onset_distribution.json").write_text(json.dumps(out, indent=2))
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
