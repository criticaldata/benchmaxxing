"""Rescore a committed ``solo_records.jsonl`` under the option-identity flip, from its own rows.

No model call and no cache: every row already stores the two answers the model gave. For each row
the twin is rebuilt from the manifest, each answer is mapped to the option it names
(``benchmaxxing.analysis.chosen_option``), and ``flipped`` is recomputed as "a different option on
the cued twin". The value the file carried is kept as ``text_changed``, which is what it was: the
two answer strings differ.

Why this exists. ``longest_option`` and ``lexical_overlap`` rewrite the text of one wrong option.
A model that picks that option on both twins returns two different strings for one choice, and a
string comparison counts it as a flip. A solo stage that replays from its cache is regenerated by
``reproduce.py --stage solo``; this script gives the same answer for a file whose stage no longer
replays (a cache that is not committed, or a cue builder that has changed since the run), and for
any published tag, because it needs only the rows and the manifest.

A cued answer that is not an option of the rebuilt twin (the cue builder changed after some runs,
so the rewritten text differs) is matched by prefix: both rewriting cues append to the option's
clean text and never touch the rest. Such rows are counted in ``matched_by_prefix``.

Usage
-----
    python experiments/medqa/rescore_solo_records.py --manifest <manifest.csv> \\
        --records experiments/medqa/results/solo_records.jsonl            # report only
    python experiments/medqa/rescore_solo_records.py --manifest <manifest.csv> \\
        --records <in.jsonl> --out-records <out.jsonl> --out-summary <out.json>
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from benchmaxxing.analysis import (  # noqa: E402
    FlipRecord, chosen_option, failure_vector, flip_rate, lineage_overlap_test,
    susceptibility_matrix, text_changed_rate,
)
from benchmaxxing.cues.text import build_text_twin  # noqa: E402
from benchmaxxing.data import load_cases  # noqa: E402
from benchmaxxing.schema import Condition  # noqa: E402


def _rows(path):
    return [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]


def _cued_key(twin, answer):
    """The option a cued-side answer names, and whether it took the prefix rule to find it."""
    key = chosen_option(twin, Condition.CONTAMINATED, answer)
    if key[0] == "option" or not isinstance(answer, str) or not answer:
        return key, False
    # The stored text is not an option of the twin as the current builder makes it. A rewriting
    # cue only appends, so the option it was made from is the clean option the text starts with.
    clean = list(twin.clean["options"])
    hits = [i for i, text in enumerate(clean) if text and answer.startswith(text + " ")]
    if not hits:
        return key, False
    return ("option", max(hits, key=lambda i: len(clean[i]))), True


def rescore(rows, cases_by_id):
    """Return ``(rescored rows, FlipRecords, per (model, cue) counts)`` for saved solo rows."""
    out, records, counts = [], [], {}
    for row in rows:
        case = cases_by_id.get(str(row["case_id"]))
        if case is None:
            raise SystemExit(f"case {row['case_id']!r} is not in the manifest: wrong manifest for these rows")
        twin = build_text_twin(case, row["cue"])
        clean, cued = row["clean"], row["contaminated"]
        stored = bool(row["text_changed"]) if row.get("text_changed") is not None else bool(row["flipped"])
        clean_key = chosen_option(twin, Condition.CLEAN, clean)
        cued_key, by_prefix = _cued_key(twin, cued)
        flipped = clean_key != cued_key
        c = counts.setdefault((row["model"], row["cue"]), {
            "n": 0, "text_changed": 0, "flipped": 0, "same_option_text_rewritten": 0,
            "matched_by_prefix": 0, "names_no_option": 0, "stored_flag_is_not_the_text_comparison": 0})
        c["n"] += 1
        c["text_changed"] += stored
        c["flipped"] += flipped
        c["same_option_text_rewritten"] += stored and not flipped
        c["matched_by_prefix"] += by_prefix
        c["names_no_option"] += clean_key[0] != "option" or cued_key[0] != "option"
        c["stored_flag_is_not_the_text_comparison"] += stored != (clean != cued)
        new_row = {}
        for k, v in row.items():  # the saved column order, with text_changed right after flipped
            if k == "text_changed":
                continue
            new_row[k] = flipped if k == "flipped" else v
            if k == "flipped":
                new_row["text_changed"] = stored
        out.append(new_row)
        records.append(FlipRecord(
            case_id=str(row["case_id"]), cue_type=row["cue"], model=row["model"], clean_answer=clean,
            contaminated_answer=cued, ground_truth=twin.ground_truth, flipped=flipped,
            clean_correct=row.get("clean_correct"), contaminated_correct=row.get("contaminated_correct"),
            text_changed=stored))
    return out, records, counts


def summarize(records, counts) -> dict:
    """The aggregate ``reproduce.py --stage solo`` writes, recomputed from rescored records."""
    by_model: dict = {}
    for r in records:
        by_model.setdefault(r.model, []).append(r)
    sm = susceptibility_matrix(by_model)
    try:
        overlap = lineage_overlap_test({m: failure_vector(rs) for m, rs in by_model.items()},
                                       {m: "gemini" for m in by_model}, metric="phi",
                                       n_permutations=2000, seed=0)
    except Exception as exc:  # noqa: BLE001  one model has no pair to correlate, as in reproduce.py
        overlap = {"error": str(exc)}
    return {
        "n_records": len(records),
        "flip_rate_by_model": {m: flip_rate(rs) for m, rs in by_model.items()},
        "text_changed_rate_by_model": {m: text_changed_rate(rs) for m, rs in by_model.items()},
        "susceptibility_matrix": {"models": sm["models"], "cues": sm["cues"], "matrix": sm["matrix"].tolist()},
        "overlap": overlap,
        "counts": {f"{model}|{cue}": c for (model, cue), c in sorted(counts.items())},
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--manifest", required=True, help="the manifest the rows' case ids come from")
    ap.add_argument("--records", required=True, help="a saved solo_records.jsonl")
    ap.add_argument("--out-records", default=None, help="write the rescored rows here")
    ap.add_argument("--out-summary", default=None, help="write the recomputed aggregate here")
    args = ap.parse_args(argv)

    rows = _rows(args.records)
    wanted = {str(r["case_id"]) for r in rows}
    cases_by_id = {str(c.case_id): c for c in load_cases(args.manifest) if str(c.case_id) in wanted}
    out, records, counts = rescore(rows, cases_by_id)
    summary = summarize(records, counts)
    for key, c in summary["counts"].items():
        print(f"{key}: text changed {c['text_changed']}/{c['n']}, flipped {c['flipped']}/{c['n']} "
              f"(same option, text rewritten: {c['same_option_text_rewritten']}; matched by prefix: "
              f"{c['matched_by_prefix']})")
    if args.out_records:
        Path(args.out_records).write_text("".join(json.dumps(r) + "\n" for r in out))
    if args.out_summary:
        Path(args.out_summary).write_text(json.dumps(summary, indent=2, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
